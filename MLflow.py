import mlflow
import os
import pandas as pd
import dagshub
from transformers import pipeline

# Initialize DagsHub for MLflow tracking
dagshub.init(repo_owner='ravishanker12784', repo_name='MLFLOW-Gen-AI', mlflow=True)
mlflow.set_tracking_uri("https://dagshub.com/ravishanker12784/MLFLOW-Gen-AI.mlflow")

eval_data = pd.DataFrame(
    {
        "inputs": [
            "What is MLflow?",
            "What is Spark?",
        ],
        "ground_truth": [
            "MLflow is an open-source platform for managing the end-to-end machine learning (ML) "
            "lifecycle. It was developed by Databricks, a company that specializes in big data and "
            "machine learning solutions. MLflow is designed to address the challenges that data "
            "scientists and machine learning engineers face when developing, training, and deploying "
            "machine learning models.",
            "Apache Spark is an open-source, distributed computing system designed for big data "
            "processing and analytics. It was developed in response to limitations of the Hadoop "
            "MapReduce computing model, offering improvements in speed and ease of use. Spark "
            "provides libraries for various tasks such as data ingestion, processing, and analysis "
            "through its components like Spark SQL for structured data, Spark Streaming for "
            "real-time data processing, and MLlib for machine learning tasks",
        ],
    }
)

mlflow.set_experiment("LLM Evaluation Local")

with mlflow.start_run() as run:
    # Using the valid 'text-generation' task name supported by the pipeline
    local_pipeline = pipeline("text-generation", model="google/flan-t5-small")

    # Log the Hugging Face pipeline as an MLflow model
    logged_model_info = mlflow.transformers.log_model(
        transformers_model=local_pipeline,
        artifact_path="model"
    )

    # Evaluate the model using standard metrics (Rouge, Toxicity, Latency)
    results = mlflow.evaluate(
        logged_model_info.model_uri,
        eval_data,
        targets="ground_truth",
        model_type="question-answering",
        extra_metrics=[mlflow.metrics.toxicity(), mlflow.metrics.latency()]
    )

    print(f"See aggregated evaluation results below: \n{results.metrics}")

    # Evaluation result for each data record
    eval_table = results.tables["eval_results_table"]
    df = pd.DataFrame(eval_table)
    df.to_csv('eval.csv')
    print(f"See evaluation table below: \n{eval_table}")